// Ο δικός μας αποκωδικοποιητής MP3 (MPEG-1 Layer III και η επέκτασή του στις χαμηλές συχνότητες), γραμμένος από τα πρότυπα ISO/IEC
// 11172-3 και 13818-3.
//
// ΤΙ ΚΑΝΕΙ. Ένα καρέ τη φορά: κεφαλίδα, πλευρική πληροφορία, η «δεξαμενή» των κύριων δεδομένων (τα δεδομένα ενός καρέ
// μπορεί να αρχίζουν μέσα σε προηγούμενα), συντελεστές κλίμακας, κώδικες Huffman, αποκβάντιση, στέρεο (μέσο/διαφορά και
// έντασης), μείωση αναδίπλωσης, αντίστροφος MDCT με τα τέσσερα παράθυρα, επικάλυψη, και η τράπεζα σύνθεσης 32 ζωνών.
// Βγάζει 1152 δείγματα ανά κανάλι, κινητής υποδιαστολής, στην κλίμακα −1 … +1.
//
// ΑΚΡΙΒΕΙΑ. Το πρότυπο δεν ορίζει την έξοδο μπιτ προς μπιτ (είναι αριθμητική πραγματικών). Γι' αυτό υπάρχουν δύο δρόμοι:
// ο ΑΚΡΙΒΗΣ (setExact) εκτελεί τους τύπους του προτύπου όπως είναι γραμμένοι, σε διπλή ακρίβεια, αργά· είναι ο μάρτυρας.
// Ο γρήγορος πρέπει να δίνει το ίδιο με τον ακριβή μέσα σε ανοχή που γράφεται δίπλα σε κάθε μέτρηση.
//
// ΑΣΦΑΛΕΙΑ. Τίποτα από όσα γράφει το αρχείο δεν γίνεται πιστευτό χωρίς έλεγχο· ο αναγνώστης μπιτ δεν διαβάζει ποτέ πέρα
// από τα δεδομένα που έχει. Χαλασμένα δεδομένα δίνουν κατάσταση λάθους ή σιωπή, όχι κατάρρευση.
#pragma once

#include <cstddef>
#include <cstdint>
#include <memory>

namespace orpheic::mp3 {

enum class Status {
    Ok,
    Truncated,     // τα δεδομένα τελείωσαν πριν από το καρέ
    NotAFrame,     // εδώ δεν αρχίζει καρέ (συγχρονισμός, απαγορευμένες τιμές)
    Unsupported,   // έγκυρο καρέ που αυτός ο αποκωδικοποιητής δεν αναλαμβάνει (Layer I/II, χαμηλές συχνότητες δειγματοληψίας)
    BadData,       // το καρέ παραβαίνει το πρότυπο· βγήκε ό,τι μπορούσε να βγει (ή σιωπή)
    NoEarlierData  // τα κύρια δεδομένα αρχίζουν σε προηγούμενο καρέ που δεν έχουμε (αρχή ροής, μετά από μετακίνηση): σιωπή
};

struct FrameHead {
    int version = 0;       // 1 = ISO/IEC 11172-3 (32, 44,1, 48 kHz) · 2 = ISO/IEC 13818-3, χαμηλές συχνότητες (16, 22,05, 24 kHz)
    int layer = 0;         // 1, 2, 3
    bool crc = false;      // ακολουθεί λέξη ελέγχου 16 μπιτ μετά την κεφαλίδα
    int bitrate = 0;       // bit/s· 0 = «ελεύθερη μορφή» (το μήκος του καρέ το ξέρει όποιος το έκοψε)
    int sampleRate = 0;
    bool padding = false;
    int mode = 0;          // 0 στέρεο · 1 κοινό στέρεο · 2 δύο ανεξάρτητα κανάλια · 3 ένα κανάλι
    bool intensity = false, midSide = false;   // μόνο στο κοινό στέρεο
    int channels = 0;
    int samples = 0;       // ανά κανάλι σε αυτό το καρέ
    int frameBytes = 0;    // 0 στην ελεύθερη μορφή
    int sideBytes = 0;
};

// Μόνο η κεφαλίδα των 4 bytes.
Status parseHead(const uint8_t *p, size_t n, FrameHead &h);

// Τι βρήκε ο αποκωδικοποιητής στη ροή (για τις δοκιμές: ποιοι δρόμοι του προτύπου ασκήθηκαν πραγματικά).
struct Stats {
    uint64_t frames = 0, granules = 0;          // granules: ανά κανάλι
    uint64_t blockType[4] = {}, mixed = 0;
    uint64_t msGranules = 0, intensityGranules = 0, intensityBands = 0;
    uint64_t scfsiUsed = 0, preflag = 0, scaleOne = 0;
    uint64_t scfsiAfterShort = 0;               // ομάδες ζωνών που «κληρονομούν» συντελεστές από πρώτο granule που ήταν κοντό μπλοκ (εκτός προτύπου)
    uint64_t table[32] = {}, count1Table[2] = {};
    uint64_t linbitsValues = 0;                 // τιμές που χρειάστηκαν τα επιπλέον μπιτ (≥ 15)
    uint64_t count1Overrun = 0;                 // τετράδες που πέρασαν το τέλος των μπιτ του granule
    uint64_t bigOverrun = 0;                    // ζεύγη που πέρασαν το τέλος των μπιτ του granule
    uint64_t stuffingBits = 0;
    uint64_t crcFrames = 0, crcBad = 0;
    uint64_t noEarlierData = 0, badFrames = 0;
    // «Αυτό δεν είναι ήχος» (βλ. ΤΙ ΔΕΝ ΕΙΝΑΙ ΗΧΟΣ στο mp3decoder.cpp): γραμμές φάσματος που μηδενίστηκαν επειδή ήταν πολύ πάνω από κάθε
    // ήχο που χωρά στη μέγιστη στάθμη, και granule (ανά κανάλι) που σίγησαν ολόκληρα· και η μεγαλύτερη ενέργεια granule που πέρασε ως ήχος.
    uint64_t absurdLines = 0, absurdGranules = 0;
    // Καρέ που βρήκαν ότι το ΠΡΟΗΓΟΥΜΕΝΟ δήλωσε περισσότερα μπιτ κύριων δεδομένων απ' όσα χωρούν πριν από την αρχή των δικών τους
    // (το προηγούμενο «μπήκε» στα δικά τους): κάτω από 8 μπιτ, και από 8 και πάνω. Βλ. ΤΟ ΠΡΟΗΓΟΥΜΕΝΟ ΚΑΡΕ ΠΑΤΑ ΣΤΟ ΕΠΟΜΕΝΟ στο mp3decoder.cpp.
    uint64_t overlapSmall = 0, overlapBig = 0, overlapHuge = 0;   // 1-7 μπιτ · 8 και πάνω · από αυτά, 64 και πάνω
    double loudestGranule = 0;
    uint64_t freeFormat = 0;
    uint64_t reservoirMax = 0;                  // η μεγαλύτερη τιμή main_data_begin
    uint64_t positionSeen[6][32] = {};          // στέρεο έντασης, χαμηλές συχνότητες: πόσες ζώνες είχαν θέση [μήκος συντελεστή σε μπιτ][τιμή]
    // Πού πάει ο χρόνος (μόνο όταν timing = true· το ίδιο το χρονόμετρο κοστίζει, άρα όχι μέσα σε μέτρηση ταχύτητας). Σε ns.
    bool timing = false;
    double nsFront = 0;      // κεφαλίδα, πλευρική πληροφορία, δεξαμενή
    double nsScale = 0;      // συντελεστές κλίμακας
    double nsHuffman = 0, nsRequant = 0, nsStereo = 0, nsHybrid = 0, nsSynth = 0;
    // Για το τελευταίο καρέ μόνο (μηδενίζονται σε κάθε decode): τι ασυνήθιστο συνέβη, για να ταιριάζει με διαφορές στη σύγκριση.
    uint32_t flags = 0;                         // 1 τετράδα πέρα από το τέλος · 2 ζεύγος πέρα από το τέλος · 4 μπιτ γεμίσματος · 8 οι τετράδες έφτασαν τη γραμμή 576 με μπιτ να περισσεύουν
    int note[4] = {};                           // [0] μπιτ που περίσσεψαν ή έλειψαν στην τελευταία τέτοια περίπτωση · [1] η γραμμή όπου συνέβη
};

class Decoder {
public:
    Decoder();
    ~Decoder();
    Decoder(const Decoder &) = delete;
    Decoder &operator=(const Decoder &) = delete;

    // true = οι τύποι του προτύπου κατά γράμμα, σε διπλή ακρίβεια (ο μάρτυρας)· false = ο γρήγορος δρόμος.
    void setExact(bool on);
    void setStats(Stats *s);
    void setDebugFrame(long frame);       // γράφει στο stderr τις ζώνες του στέρεο έντασης αυτού του καρέ (χρειάζεται setStats)

    // Ξεχνά τη δεξαμενή, την επικάλυψη και το ιστορικό της τράπεζας σύνθεσης (αρχή ροής, μετακίνηση).
    void reset();
    // «Εδώ χάθηκαν δεδομένα»: ξεχνά ΜΟΝΟ τη δεξαμενή (όχι την επικάλυψη και το ιστορικό της σύνθεσης). Το λέει όποιος κόβει τα πακέτα
    // όταν ανάμεσα σε δύο καρέ βρήκε κάτι που δεν ήταν καρέ: τα επόμενα καρέ δεν πρέπει να διαβάσουν «προηγούμενα δεδομένα» από bytes
    // που δεν είναι πια τα προηγούμενά τους (θα έβγαινε δυνατός θόρυβος αντί για σιωπή).
    void lostData();

    // ΕΝΑ ολόκληρο καρέ: p[0 .. n) από τη λέξη συγχρονισμού ως το τελευταίο του byte. Μετά από Ok, BadData ή NoEarlierData
    // υπάρχουν head().samples δείγματα ανά κανάλι στο channel(c) (σιωπή όπου δεν γινόταν αλλιώς)· με τις άλλες καταστάσεις τίποτα.
    Status decode(const uint8_t *p, size_t n);

    const FrameHead &head() const;
    const float *channel(int c) const;

private:
    struct Impl;
    std::unique_ptr<Impl> d_;
};

}  // namespace orpheic::mp3
