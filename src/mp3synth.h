// Η τράπεζα σύνθεσης του MP3 (ISO/IEC 11172-3, σχήμα A.2), ο γρήγορος δρόμος σε απλή ακρίβεια.
//
// Δίνει ό,τι και το exact::synth του mp3exact.h (το διάγραμμα του προτύπου κατά γράμμα, σε διπλή ακρίβεια) μέσα σε ανοχή
// στρογγύλευσης: η δοκιμή του το αποδεικνύει δείγμα προς δείγμα. Το πώς και το γιατί: mp3synth.cpp.
#pragma once


namespace orpheic::mp3 {

// Η μνήμη της τράπεζας για ΕΝΑ κανάλι. Σκέτα δεδομένα: αντιγράφεται με ανάθεση, δεν δείχνει πουθενά.
//
// Το πρότυπο κρατά 1024 τιμές V (16 χρονικές θέσεις επί 64). Από τις 64 τιμές κάθε θέσης μόνο 32 είναι καινούριοι αριθμοί (βλ.
// mp3synth.cpp, «V από C»), άρα εδώ κάθε χρονική θέση είναι μία σειρά 32 τιμών, και μία ακόμα τιμή στο `mid`.
//
// ΔΥΟ ΜΙΣΑ ΠΟΥ ΕΝΑΛΛΑΣΣΟΝΤΑΙ. Κάθε granule γράφει τις 18 σειρές του στο ένα μισό· το άλλο μισό κρατά ακόμη τις 18 του
// προηγούμενου, και από αυτές το παράθυρο χρειάζεται τις 15 τελευταίες. Στην επόμενη κλήση οι ρόλοι αλλάζουν (`last`). Έτσι καμία
// σειρά δεν μετακινείται ποτέ: ούτε η μετακίνηση 7,7 kB ανά θέση του διαγράμματος του προτύπου, ούτε αντιγραφή της ιστορίας στο
// τέλος κάθε granule. Το παράθυρο διαλέγει για κάθε σειρά μιας θέσης αν θα τη διαβάσει από το παλιό μισό ή από το νέο.
//
// Η στοίχιση στα 32 bytes είναι ΑΠΑΙΤΗΣΗ του δρόμου SSE2 (διαβάζει τις σειρές με στοιχισμένες εντολές). Τη δίνει μόνος του ο
// μεταγλωττιστής σε κάθε κανονική δήλωση, και το new της C++17· μόνο ένα malloc με το χέρι ή ένα #pragma pack θα την έσπαγε.
struct SynthState {
    alignas(32) float rows[2][18 * 32] = {};
    alignas(32) float mid[24] = {};      // τα 18 C[16] του προηγούμενου granule· οι υπόλοιπες μένουν μηδέν
    int last = 0;                        // το μισό που έγραψε η προηγούμενη κλήση (η ιστορία)· η επόμενη γράφει στο άλλο
};

// Αρχή ροής, ή μετά από άλμα: όλη η ιστορία μηδέν (ό,τι και ένα καινούριο SynthState).
void synthReset(SynthState &st);

// in:  576 δείγματα υποζωνών ενός granule ενός καναλιού, in[32·θέση + υποζώνη], θέση 0 … 17 (χρόνος), υποζώνη 0 … 31.
// out: 576 δείγματα ήχου (πρώτα τα 32 της θέσης 0).
// Τα in και out δεν χρειάζονται καμία στοίχιση. Μπορούν να είναι ο ΙΔΙΟΣ πίνακας: όλη η είσοδος διαβάζεται πριν γραφτεί η
// πρώτη έξοδος (η δοκιμή το ελέγχει). Μερική επικάλυψη δεν επιτρέπεται.
void synth(SynthState &st, const float *in, float *out);

// Ποιον δρόμο τρέχει αυτός ο επεξεργαστής, για να τυπώνεται δίπλα στους αριθμούς.
const char *synthKernelText();

// Διακόπτες δοκιμής. Αλλάζουν τον δρόμο για ΟΛΗ τη διεργασία· όχι την ώρα που άλλο νήμα τρέχει το synth.
void synthUseBasicOnly(bool on);   // true = μόνο ό,τι έχει κάθε x86-64 (SSE2). Στον ARM64 δεν αλλάζει τίποτα (το NEON είναι η βάση).
void synthUseScalar(bool on);      // true = ο δρόμος της σκέτης C++, χωρίς καμία εντολή ειδική του επεξεργαστή.

}  // namespace orpheic::mp3
