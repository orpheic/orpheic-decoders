// Το «υβριδικό» στάδιο του αποκωδικοποιητή MP3, γρήγορα: μείωση αναδίπλωσης, αντίστροφος MDCT, παράθυρο, επικάλυψη με το
// προηγούμενο granule, αντιστροφή συχνότητας (ISO/IEC 11172-3, 2.4.3.4.10.1 ως 2.4.3.4.10.5).
//
// Προδιαγραφή του είναι το exact::hybrid του mp3exact.h (ο τύπος του προτύπου κατά γράμμα, σε διπλή ακρίβεια): η έξοδος εδώ
// είναι η ίδια μέσα σε στρογγύλευση απλής ακρίβειας. Το πώς βγαίνει ο γρήγορος δρόμος από τον τύπο, βήμα προς βήμα, είναι
// γραμμένο στο mp3hybrid.cpp· ότι δίνει το ίδιο το αποδεικνύει η δοκιμή του.
//
// ΔΙΑΤΑΞΗ, ίδια με του mp3exact.h: 18 σειρές επί 32 υποζώνες, θέση = 32·σειρά + υποζώνη.
//   · είσοδος: σειρά = γραμμή συχνότητας μέσα στην υποζώνη (0 … 17) στα μακριά μπλοκ· στα κοντά σειρά = 6·παράθυρο + γραμμή
//   · έξοδος: σειρά = χρονική θέση (0 … 17), 32 δείγματα υποζωνών ανά θέση, όπως τα θέλει η τράπεζα σύνθεσης.
// Μια σειρά είναι 32 συνεχόμενοι float, ένας ανά υποζώνη: ο ίδιος μικρός μετασχηματισμός τρέχει σε 8 (ή 4) υποζώνες μαζί.
#pragma once


namespace orpheic::mp3 {

// Ό,τι περνά από το ένα granule στο επόμενο, ανά κανάλι.
struct HybridState {
    // Το δεύτερο μισό του προηγούμενου μπλοκ, έτοιμο να προστεθεί: θέση = 32·σειρά + υποζώνη. ΠΡΟΣΟΧΗ: είναι αποθηκευμένο με
    // το πρόσημο της αντιστροφής συχνότητας ήδη μέσα (περιττή σειρά περιττής υποζώνης = αντίθετο πρόσημο), γιατί έτσι το
    // πρόσημο δεν κοστίζει καμία πράξη (βλ. mp3hybrid.cpp, «ΤΟ ΠΡΟΣΗΜΟ»). Δεν είναι για να το διαβάζει κανείς άλλος.
    alignas(32) float overlap[18 * 32] = {};
    // Πόσες πρώτες υποζώνες μπορεί να έχουν επικάλυψη διάφορη του μηδενός. ΑΝΑΛΛΟΙΩΤΟ: overlap[32·σειρά + sb] είναι ακριβώς
    // μηδέν για κάθε sb ≥ live. Έτσι ένα granule με λίγες υποζώνες δεν αγγίζει καν τις υπόλοιπες.
    int live = 0;
};

// Αρχή ροής ή μετά από άλμα: καμία επικάλυψη από πριν.
void hybridReset(HybridState &st);

// x:   576 τιμές πριν από τον μετασχηματισμό (βλ. ΔΙΑΤΑΞΗ). Είναι πρόχειρο του καλούντος: η συνάρτηση επιτρέπεται να το
//      αλλάξει (σήμερα δεν το αλλάζει). Δεν πρέπει να επικαλύπτεται με το out.
// blockType 0 … 3 όπως στο πρότυπο. mixed (μετρά μόνο με blockType 2): οι υποζώνες 0 και 1 είναι μακριές με το κανονικό
//      παράθυρο, οι υπόλοιπες κοντές.
// subbands: πόσες πρώτες υποζώνες μπορεί να έχουν τιμές διάφορες του μηδενός (0 … 32). Ο καλών ΕΓΓΥΑΤΑΙ ότι κάθε
//      x[32·σειρά + sb] με sb ≥ subbands ΕΙΝΑΙ μηδέν (η συνάρτηση διαβάζει μερικά από αυτά τα μηδενικά και βασίζεται σε αυτό).
// out: 576 δείγματα υποζωνών, out[32·χρονική θέση + υποζώνη]: γράφονται και τα 576, πάντα.
// Καμία υπόθεση για τη στοίχιση των x και out.
void hybrid(HybridState &st, float *x, int blockType, bool mixed, int subbands, float *out);

// Ποιος δρόμος τρέχει σε αυτό το μηχάνημα, για τα μηνύματα της δοκιμής.
const char *hybridKernelText();

// Διακόπτες δοκιμής. BasicOnly: μόνο ό,τι έχει κάθε x86-64 (SSE2). Scalar: ο απλός δρόμος της C++, μία υποζώνη τη φορά.
// Αλλάζουν ποιος δρόμος τρέχει ΓΙΑ ΟΛΑ τα νήματα· η κατάσταση (HybridState) είναι ίδια για όλους τους δρόμους.
void hybridUseBasicOnly(bool on);
void hybridUseScalar(bool on);

}  // namespace orpheic::mp3
