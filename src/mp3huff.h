// Ο γρήγορος πυρήνας των κωδίκων Huffman ενός granule ενός καναλιού (ISO/IEC 11172-3, 2.4.1.7 και 2.4.3.4.6).
//
// Δίνει ΑΚΡΙΒΩΣ ό,τι και ο κατά γράμμα πυρήνας exact::huffman του mp3exact.h, για οποιαδήποτε είσοδο: τον ίδιο αριθμό
// γραμμών, τις ίδιες 576 τιμές, την ίδια τελική θέση, τις ίδιες σημειώσεις. Το πώς (πίνακες, παράθυρο 64 μπιτ, ο
// προσεκτικός δρόμος στις άκρες) εξηγείται στο mp3huff.cpp. Το αποδεικνύει η δοκιμή του.
#pragma once


#include <cstddef>
#include <cstdint>

#include "mp3exact.h"

namespace orpheic::mp3 {

// data:  τα bytes των κύριων δεδομένων· υπάρχουν τα μπιτ [0, endBits). Ο καλών εγγυάται ότι 8 ακόμη bytes μετά το τελευταίο
//        byte δεδομένων διαβάζονται (το περιεχόμενό τους είναι ό,τι να 'ναι και δεν επηρεάζει ΠΟΤΕ το αποτέλεσμα: τα μπιτ από
//        το endBits και πέρα διαβάζονται ως μηδέν, ακριβώς όπως στο exact::Bits). Δεν διαβάζεται ποτέ τίποτα έξω από το
//        data[0 … ⌈endBits/8⌉ + 8).
// pos:   μπαίνει το μπιτ όπου αρχίζουν οι κώδικες αυτού του granule· βγαίνει εκεί που σταμάτησε η ανάγνωση (η ίδια τιμή με
//        το exact::Bits::pos μετά το exact::huffman, και όταν είναι μετά το gend ή μετά το endBits).
// gend:  το μπιτ όπου τελειώνουν τα δεδομένα αυτού του granule (gend ≤ endBits· το pos μπορεί να είναι ήδη ≥ gend).
// in:    ακριβώς το exact::HuffmanIn. Τιμές έξω από όσα επιτρέπει το πρότυπο (big > 576, πίνακας έξω από 0 … 31) δεν
//        γράφουν ποτέ έξω από το is[0 … 575]: το big κόβεται στο 576, ο άγνωστος πίνακας μετρά ως «δεν χρησιμοποιείται».
// is:    γράφονται 576 τιμές, is[0 … 575]. Ο καλών δίνει χώρο για 576 + 8· τα 8 τελευταία δεν τα αγγίζουμε.
// notes: προαιρετικό· κάθε πεδίο αλλάζει όπως θα το άλλαζε το exact::huffman (προσθέτει, δεν μηδενίζει).
// Επιστρέφει ό,τι και το exact::huffman: πόσες γραμμές διαβάστηκαν, ή −1 αν μια περιοχή που φτάσαμε διαλέγει τον πίνακα 4
// ή 14 (τότε is = όλο μηδέν).
int huffman(const uint8_t *data, size_t endBits, size_t &pos, size_t gend, const exact::HuffmanIn &in, int16_t *is,
            exact::HuffmanNotes *notes = nullptr);

// Ποιος δρόμος είναι ενεργός, για τις αναφορές («two-pair tables · shlx/shrx» κ.λπ.).
const char *huffmanKernelText();

// Διακόπτης δοκιμής: μόνο ό,τι έχει κάθε x86-64 (ολισθήσεις με τον CL αντί για SHLX/SHRX). Αλλού δεν αλλάζει τίποτα.
void huffmanUseBasicOnly(bool on);

// Διακόπτης δοκιμής: όλα από τον προσεκτικό δρόμο (αυτόν που κανονικά δουλεύει μόνο στις άκρες), για να ελέγχεται κι αυτός
// σε κάθε κώδικα κάθε πίνακα.
void huffmanUseCarefulOnly(bool on);

// Πόσα bytes πιάνουν οι πίνακες αναζήτησης. Χτίζονται μία φορά από το mp3tables.inc, στην πρώτη κλήση οποιασδήποτε
// συνάρτησης εδώ (κλάσμα του χιλιοστού του δευτερολέπτου)· όποιος δεν θέλει να πέσει αυτό πάνω στο πρώτο granule που θα
// ακουστεί, καλεί αυτή τη συνάρτηση όταν φτιάχνει τον αποκωδικοποιητή.
size_t huffmanTableBytes();

// Για τη δοκιμή: αληθές αν οι πίνακες του προτύπου είναι αυτό που υποθέτει το σχέδιο (κανένας κώδικας αρχή άλλου, κάθε
// σειρά μπιτ κάποιος κώδικας, τα μήκη μέσα στα όρια του παραθύρου). Εξαρτάται μόνο από το mp3tables.inc, όχι από την είσοδο.
// `text`, αν δοθεί: μια γραμμή ανά σύνολο κωδίκων με τα μεγέθη των πινάκων του.
bool huffmanSelfCheck(char *text = nullptr, size_t textSize = 0);

#ifdef MP3HUFF_COVERAGE
// Μόνο στο χτίσιμο κάλυψης: πόσες φορές χρησιμοποιήθηκε κάθε θέση κάθε πίνακα αναζήτησης, ανά δρόμο. Κάθε θέση είναι
// προσιτή από κάθε δρόμο που έχει τον πίνακά της (ο γρήγορος δρόμος φτάνει στον G και από το τελευταίο ζεύγος μιας
// περιοχής), άρα σε μια πλήρη δοκιμή πρέπει used == entries σε κάθε γραμμή.
struct HuffmanCoverageRow {
    char name[72];
    uint32_t entries;    // θέσεις του πίνακα
    uint32_t used;       // όσες χρησιμοποιήθηκαν τουλάχιστον μία φορά
    uint32_t minUses;    // οι λιγότερες χρήσεις μιας θέσης
    uint32_t firstUnused;   // η πρώτη θέση που δεν χρησιμοποιήθηκε (όταν used < entries)
    uint64_t uses;       // όλες οι χρήσεις
};
size_t huffmanCoverage(HuffmanCoverageRow *rows, size_t max);
void huffmanCoverageReset();
#endif

}  // namespace orpheic::mp3
