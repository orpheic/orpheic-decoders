// διαφορετικά", και ταυτόχρονα να είναι γρήγορος». Μετρημένο την ίδια μέρα: το ίδιο MP3 έβγαινε με ένα δείγμα στα 5,7 εκατ. με άλλο
// τελευταίο bit στα Windows από ό,τι στο Linux, γιατί το std::cos/sin/tan/pow κάθε συστήματος δίνει ελαφρώς άλλη απάντηση (89 από
// τις 13.288 τιμές του ακριβούς δρόμου). Εδώ ΔΕΝ ρωτιέται κανένα σύστημα: κάθε τιμή είναι γραμμένη, υπολογισμένη μία φορά με 60
// ψηφία και στρογγυλεμένη σωστά στον πλησιέστερο double (tool/mp3consts_gen.py → mp3consts_tables.inc). Ίδια σε κάθε σύστημα και
// μεταγλωττιστή, και η ακριβέστερη που χωρά ένας double. Το std::sqrt μένει: το IEEE 754 το ορίζει ακριβώς (σωστή στρογγύλευση).
//
// Οι γωνίες: κάθε γωνία του αποκωδικοποιητή είναι ρητό πολλαπλάσιο του π με παρονομαστή που διαιρεί το 576 (64 της σύνθεσης,
// 72 και 24 του IMDCT, 18 του 9-σημείων), οπότε δίνεται ως ακέραιο m: η γωνία π·m/576.
#include <cmath>

namespace orpheic::mp3::consts {

#include "mp3consts_tables.inc"

// cos(π·m/576) για κάθε ακέραιο m.
inline double cosPi576(long m)
{
    m %= 1152;
    if (m < 0) m += 1152;          // [0, 2π)
    if (m > 576) m = 1152 - m;     // cos(2π − x) = cos x
    return kCosPi576[m];
}
// sin(π·m/576) = cos(π/2 − π·m/576).
inline double sinPi576(long m) { return cosPi576(288 - m); }
// tan(π·m/576), μόνο για m = 8j, 0 ≤ j < 36 (όσες χρειάζεται ο αποκωδικοποιητής· αλλιώς NaN, για να φανεί αμέσως).
inline double tanPi576(int m)
{
    return (m >= 0 && m % 8 == 0 && m / 8 < 36) ? kTanPi576x8[m / 8] : std::nan("");
}
// v^(4/3) για 0 ≤ v ≤ 8206 (όλες οι τιμές ενός δείγματος του προτύπου)· έξω από αυτό NaN.
inline double pow43(int v) { return (v >= 0 && v < 8207) ? kPow43[v] : std::nan(""); }
// 2^(q/4) για κάθε ακέραιο q, ακριβώς: ldexp(2^(r/4), e) με q = 4e + r, 0 ≤ r < 4 (το ldexp δεν στρογγυλεύει).
inline double pow2q(int q)
{
    const int r = q & 3;           // ο θετικός υπόλοιπος και για αρνητικό q (συμπλήρωμα ως προς 2)
    return std::ldexp(kRoot4[r], (q - r) / 4);
}

}  // namespace orpheic::mp3::consts
